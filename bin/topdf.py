#!/usr/bin/env python3
"""Render a generated resume to PDF.

Chrome headless, deliberately. The construction rules in jobhunt/resume.py come
from ATS parser testing — two-column layouts scrambled in 7 of 8 parsers, table
content dropped in 5 of 8, image-based text losing name and contact every time —
so the PDF has to carry REAL TEXT in a SINGLE COLUMN with no tables and no
sidebars. Chrome prints selectable text from ordinary HTML, which satisfies that;
an image-based renderer would not.

Markdown parsing is deliberately minimal. The input is generated by resume.py, so
its shape is known and fixed; a general parser would be a dependency bought for
nothing.

    bin/topdf.py out/generic.general.md            -> out/generic.general.pdf
"""
import html
import pathlib
import shutil
import subprocess
import sys
import tempfile
import time

MIN_ARGS = 2  # script plus the markdown file
RENDER_TIMEOUT_S = 60

CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

CSS = """
@page { size: Letter; margin: 0.45in 0.55in; }
* { box-sizing: border-box; }
body { font: 9.8pt/1.33 Georgia, "Times New Roman", serif; color: #111;
       margin: 0; max-width: 100%; }
h1 { font-size: 17pt; margin: 0 0 1pt; letter-spacing: .2pt; }
.contact { font-size: 9pt; color: #333; margin: 0 0 9pt; }
h2 { font-size: 10pt; text-transform: uppercase; letter-spacing: 1.1pt;
     border-bottom: .8pt solid #999; padding-bottom: 2pt;
     margin: 11pt 0 5pt; page-break-after: avoid; }
h3 { font-size: 10.2pt; margin: 7pt 0 1pt; page-break-after: avoid; }
.dates { font-size: 8.6pt; color: #555; margin: 0 0 3pt; }
p { margin: 0 0 5pt; }
ul { margin: 0 0 5pt; padding-left: 13pt; }
li { margin: 0 0 2.5pt; page-break-inside: avoid; }
.role { page-break-inside: avoid; }
"""


def _heading(marker, esc):
    """The fragments a heading emits, and whether it opened a role block.

    A role heading opens a wrapper the next heading has to close, so the caller
    needs that state back rather than inferring it from the markup.
    """
    tag = f"h{len(marker) - 1}"
    head = f"<{tag}>{esc[len(marker):]}</{tag}>"
    if marker == "### ":
        return ['<div class="role">', head], True
    return [head], False


def _para_class(lines, n):
    """The line under a heading is the contact block, or a role's dates."""
    prev = lines[n - 1].strip() if n else ""
    if prev.startswith("# "):
        return "contact"
    if prev.startswith("### "):
        return "dates"
    return ""


def to_html(md, title):
    out, in_list, in_role = [], False, False

    def close_list():
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def close_role():
        nonlocal in_role
        if in_role:
            out.append("</div>")
            in_role = False

    lines = md.splitlines()
    for n, raw in enumerate(lines):
        line = raw.rstrip()
        if not line:
            continue
        esc = html.escape(line)
        marker = next((m for m in ("### ", "## ", "# ") if line.startswith(m)), None)
        if marker:
            close_list()
            close_role()
            frags, in_role = _heading(marker, esc)
            out.extend(frags)
        elif line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{esc[2:]}</li>")
        else:
            close_list()
            # The line under a heading is the contact block or a role's dates.
            cls = _para_class(lines, n)
            out.append(f'<p class="{cls}">{esc}</p>' if cls else f"<p>{esc}</p>")
    close_list()
    close_role()
    return (f"<!doctype html><html><head><meta charset='utf-8'>"
            f"<title>{html.escape(title)}</title><style>{CSS}</style></head>"
            f"<body>{''.join(out)}</body></html>")


def main():
    if len(sys.argv) < MIN_ARGS:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    if not pathlib.Path(CHROME).exists():
        sys.exit(f"error: Chrome not found at {CHROME}; it is the renderer")
    out_pdf = pathlib.Path(sys.argv[2]) if len(sys.argv) > MIN_ARGS else src.with_suffix(".pdf")
    tmp = src.with_suffix(".render.html")
    tmp.write_text(to_html(src.read_text(), src.stem))
    # Chrome 152 writes the PDF and then never exits, so waiting on the process
    # waits forever. The file is the result: poll until it exists and stops
    # growing, then kill. Its own profile directory keeps it clear of the lock a
    # running Chrome holds.
    profile = tempfile.mkdtemp(prefix="topdf-chrome-")
    out_pdf.unlink(missing_ok=True)
    proc = subprocess.Popen(
        [CHROME, "--headless", "--disable-gpu", "--no-pdf-header-footer",
         f"--user-data-dir={profile}",
         f"--print-to-pdf={out_pdf}", tmp.resolve().as_uri()],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        deadline = time.monotonic() + RENDER_TIMEOUT_S
        while time.monotonic() < deadline and proc.poll() is None:
            if out_pdf.exists() and out_pdf.stat().st_size:
                size = out_pdf.stat().st_size
                time.sleep(0.4)
                if out_pdf.exists() and out_pdf.stat().st_size == size:
                    break
            time.sleep(0.2)
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait(timeout=10)
        shutil.rmtree(profile, ignore_errors=True)
        tmp.unlink()
    if not out_pdf.exists() or not out_pdf.stat().st_size:
        sys.exit(f"error: Chrome produced no PDF at {out_pdf}")
    print(f"{out_pdf}  ({out_pdf.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
