#!/usr/bin/env python3
"""Render a generated resume to PDF.

Chrome headless, deliberately. The construction rules in jobhunt/resume.py come
from ATS parser testing — two-column layouts scrambled in 7 of 8 parsers, table
content dropped in 5 of 8, image-based text losing name and contact every time —
so the PDF has to carry REAL TEXT in a SINGLE COLUMN with no tables and no
sidebars. Chrome prints selectable text from ordinary HTML, which satisfies that;
an image-based renderer would not.

Markdown parsing is deliberately minimal. The input is generated by resume.py, so
its shape is known and fixed; a general parser would be a dependency bought for
nothing.

    bin/topdf.py out/generic.general.md            -> out/generic.general.pdf
"""
import html
import pathlib
import subprocess
import sys

CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

CSS = """
@page { size: Letter; margin: 0.45in 0.55in; }
* { box-sizing: border-box; }
body { font: 9.8pt/1.33 Georgia, "Times New Roman", serif; color: #111;
       margin: 0; max-width: 100%; }
h1 { font-size: 17pt; margin: 0 0 1pt; letter-spacing: .2pt; }
.contact { font-size: 9pt; color: #333; margin: 0 0 9pt; }
h2 { font-size: 10pt; text-transform: uppercase; letter-spacing: 1.1pt;
     border-bottom: .8pt solid #999; padding-bottom: 2pt;
     margin: 11pt 0 5pt; page-break-after: avoid; }
h3 { font-size: 10.2pt; margin: 7pt 0 1pt; page-break-after: avoid; }
.dates { font-size: 8.6pt; color: #555; margin: 0 0 3pt; }
p { margin: 0 0 5pt; }
ul { margin: 0 0 5pt; padding-left: 13pt; }
li { margin: 0 0 2.5pt; page-break-inside: avoid; }
.role { page-break-inside: avoid; }
"""


def to_html(md, title):
    out, in_list, in_role = [], False, False

    def close_list():
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def close_role():
        nonlocal in_role
        if in_role:
            out.append("</div>")
            in_role = False

    lines = md.splitlines()
    for n, raw in enumerate(lines):
        line = raw.rstrip()
        if not line:
            continue
        esc = html.escape(line)
        if line.startswith("# "):
            close_list(); close_role()
            out.append(f"<h1>{esc[2:]}</h1>")
        elif line.startswith("## "):
            close_list(); close_role()
            out.append(f"<h2>{esc[3:]}</h2>")
        elif line.startswith("### "):
            close_list(); close_role()
            out.append('<div class="role">')
            in_role = True
            out.append(f"<h3>{esc[4:]}</h3>")
        elif line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{esc[2:]}</li>")
        else:
            close_list()
            # The line under a heading is the contact block or a role's dates.
            prev = lines[n - 1].strip() if n else ""
            cls = "contact" if prev.startswith("# ") else "dates" if prev.startswith("### ") else ""
            out.append(f'<p class="{cls}">{esc}</p>' if cls else f"<p>{esc}</p>")
    close_list(); close_role()
    return (f"<!doctype html><html><head><meta charset='utf-8'>"
            f"<title>{html.escape(title)}</title><style>{CSS}</style></head>"
            f"<body>{''.join(out)}</body></html>")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    if not pathlib.Path(CHROME).exists():
        sys.exit(f"error: Chrome not found at {CHROME}; it is the renderer")
    out_pdf = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else src.with_suffix(".pdf")
    tmp = src.with_suffix(".render.html")
    tmp.write_text(to_html(src.read_text(), src.stem))
    subprocess.run([CHROME, "--headless", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={out_pdf}", tmp.resolve().as_uri()],
                   check=True, capture_output=True)
    tmp.unlink()
    print(f"{out_pdf}  ({out_pdf.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
